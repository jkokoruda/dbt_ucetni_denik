/*
 * Port of refactoring/initiate_stg.sql.
 * Keeps STG rows unless DAT_UCTO <= the latest PS balance date, then appends
 * opening balances from PS_UCETNI_DENIK. A null cutoff deletes nothing, and
 * rows with a null DAT_UCTO stay. PS rows fill only PK, SOURCE, UCET,
 * DAT_UCTO, and SUM_TUZ; every other column is null.
 * Alias OUT_STG_UCETNI_DENIK avoids clashing with STG_UCETNI_DENIK.
 * Keboola output mapping writes this table back to STG_UCETNI_DENIK.
 */

WITH cutoff AS (
    SELECT MAX("DAT_UCTO") AS "CUTOFF_DATE"
    FROM {{ source('l2_input', 'PS_UCETNI_DENIK') }}
),

kept AS (
    SELECT
        CAST(s."PK_UCETNI_DENIK" AS VARCHAR) AS "PK_UCETNI_DENIK",
        CAST(s."SOURCE" AS VARCHAR(3)) AS "SOURCE",
        CAST(s."UCET" AS VARCHAR) AS "UCET",
        CAST(s."UCET_SHOW_AS" AS VARCHAR) AS "UCET_SHOW_AS",
        CAST(s."COUNTER_ACCOUNT" AS VARCHAR) AS "COUNTER_ACCOUNT",
        CAST(s."ID_UCETNI_DENIK" AS VARCHAR) AS "ID_UCETNI_DENIK",
        CAST(s."LAST_UPDATE" AS TIMESTAMP_NTZ) AS "LAST_UPDATE",
        CAST(s."UPDATED_BY" AS VARCHAR) AS "UPDATED_BY",
        CAST(s."UPDATED_BY_REF" AS VARCHAR) AS "UPDATED_BY_REF",
        CAST(s."UPDATED_BY_SHOW_AS" AS VARCHAR) AS "UPDATED_BY_SHOW_AS",
        CAST(s."CLEN_DPH" AS VARCHAR) AS "CLEN_DPH",
        CAST(s."CLEN_DPH_REF" AS VARCHAR) AS "CLEN_DPH_REF",
        CAST(s."CLEN_DPH_SHOW_AS" AS VARCHAR) AS "CLEN_DPH_SHOW_AS",
        CAST(s."DAT_SPLAT" AS DATE) AS "DAT_SPLAT",
        CAST(s."DAT_UHR" AS DATE) AS "DAT_UHR",
        CAST(s."DAT_VYST" AS DATE) AS "DAT_VYST",
        CAST(s."DAT_UCTO" AS DATE) AS "DAT_UCTO",
        CAST(s."DOKLAD" AS VARCHAR) AS "DOKLAD",
        CAST(s."DUZP_UCTO" AS DATE) AS "DUZP_UCTO",
        CAST(s."POSTING_PERIOD" AS VARCHAR) AS "POSTING_PERIOD",
        CAST(s."FIRMA" AS VARCHAR) AS "FIRMA",
        CAST(s."FIRMA_REF" AS VARCHAR) AS "FIRMA_REF",
        CAST(s."FIRMA_SHOW_AS" AS VARCHAR) AS "FIRMA_SHOW_AS",
        CAST(s."KURZ" AS NUMBER(18,6)) AS "KURZ",
        CAST(s."KURZ_MNOZSTVI" AS NUMBER(18,6)) AS "KURZ_MNOZSTVI",
        CAST(s."MENA" AS VARCHAR) AS "MENA",
        CAST(s."MENA_REF" AS VARCHAR) AS "MENA_REF",
        CAST(s."MENA_SHOW_AS" AS VARCHAR) AS "MENA_SHOW_AS",
        CAST(s."MODUL" AS VARCHAR) AS "MODUL",
        CAST(s."MODUL_K" AS VARCHAR) AS "MODUL_K",
        CAST(s."MODUL_K_SHOW_AS" AS VARCHAR) AS "MODUL_K_SHOW_AS",
        CAST(s."NAZ_FIRMY" AS VARCHAR) AS "NAZ_FIRMY",
        CAST(s."DIC" AS VARCHAR) AS "DIC",
        CAST(s."POPIS" AS VARCHAR) AS "POPIS",
        CAST(s."VAR_SYM" AS VARCHAR) AS "VAR_SYM",
        CAST(s."TYP_SZB_DPH_K" AS VARCHAR) AS "TYP_SZB_DPH_K",
        CAST(s."TYP_SZB_DPH_K_SHOW_AS" AS VARCHAR) AS "TYP_SZB_DPH_K_SHOW_AS",
        CAST(s."SZB_DPH" AS NUMBER(18,6)) AS "SZB_DPH",
        CAST(s."SUM_TUZ" AS NUMBER(18,2)) AS "SUM_TUZ",
        CAST(s."SUM_MEN" AS NUMBER(18,2)) AS "SUM_MEN",
        CAST(s."STAV_UZIV_K" AS VARCHAR) AS "STAV_UZIV_K",
        CAST(s."STAV_UZIV_K_SHOW_AS" AS VARCHAR) AS "STAV_UZIV_K_SHOW_AS",
        CAST(s."STREDISKO" AS VARCHAR) AS "STREDISKO",
        CAST(s."STREDISKO_REF" AS VARCHAR) AS "STREDISKO_REF",
        CAST(s."STREDISKO_SHOW_AS" AS VARCHAR) AS "STREDISKO_SHOW_AS",
        CAST(s."ID_DOKL" AS VARCHAR) AS "ID_DOKL",
        CAST(s."ZUCTOVANO" AS BOOLEAN) AS "ZUCTOVANO",
        CAST(s."VAT_ITEM" AS BOOLEAN) AS "VAT_ITEM",
        CAST(s."ACCOUNTS_SWAPPED" AS BOOLEAN) AS "ACCOUNTS_SWAPPED",
        CAST(s."ZAKAZKA" AS VARCHAR) AS "ZAKAZKA",
        CAST(s."ZAKAZKA_REF" AS VARCHAR) AS "ZAKAZKA_REF",
        CAST(s."ZAKAZKA_SHOW_AS" AS VARCHAR) AS "ZAKAZKA_SHOW_AS",
        CAST(s."PAR_SYMBOL" AS VARCHAR) AS "PAR_SYMBOL",
        CAST(s."CINNOST" AS VARCHAR) AS "CINNOST",
        CAST(s."CINNOST_REF" AS VARCHAR) AS "CINNOST_REF",
        CAST(s."CINNOST_SHOW_AS" AS VARCHAR) AS "CINNOST_SHOW_AS",
        CAST(s."ID_POLOZEK" AS VARCHAR) AS "ID_POLOZEK",
        CAST(s."BEZ_POLOZEK" AS BOOLEAN) AS "BEZ_POLOZEK"
    FROM {{ source('l2_input', 'STG_UCETNI_DENIK') }} AS s
    CROSS JOIN cutoff AS c
    WHERE c."CUTOFF_DATE" IS NULL
        OR s."DAT_UCTO" IS NULL
        OR s."DAT_UCTO" > c."CUTOFF_DATE"
),

ps_rows AS (
    SELECT
        CONCAT('PS_', "UCET", '_', TO_VARCHAR("DAT_UCTO", 'YYYYMMDD')) AS "PK_UCETNI_DENIK",
        CAST('PS' AS VARCHAR(3)) AS "SOURCE",
        CAST("UCET" AS VARCHAR) AS "UCET",
        CAST(NULL AS VARCHAR) AS "UCET_SHOW_AS",
        CAST(NULL AS VARCHAR) AS "COUNTER_ACCOUNT",
        CAST(NULL AS VARCHAR) AS "ID_UCETNI_DENIK",
        CAST(NULL AS TIMESTAMP_NTZ) AS "LAST_UPDATE",
        CAST(NULL AS VARCHAR) AS "UPDATED_BY",
        CAST(NULL AS VARCHAR) AS "UPDATED_BY_REF",
        CAST(NULL AS VARCHAR) AS "UPDATED_BY_SHOW_AS",
        CAST(NULL AS VARCHAR) AS "CLEN_DPH",
        CAST(NULL AS VARCHAR) AS "CLEN_DPH_REF",
        CAST(NULL AS VARCHAR) AS "CLEN_DPH_SHOW_AS",
        CAST(NULL AS DATE) AS "DAT_SPLAT",
        CAST(NULL AS DATE) AS "DAT_UHR",
        CAST(NULL AS DATE) AS "DAT_VYST",
        CAST("DAT_UCTO" AS DATE) AS "DAT_UCTO",
        CAST(NULL AS VARCHAR) AS "DOKLAD",
        CAST(NULL AS DATE) AS "DUZP_UCTO",
        CAST(NULL AS VARCHAR) AS "POSTING_PERIOD",
        CAST(NULL AS VARCHAR) AS "FIRMA",
        CAST(NULL AS VARCHAR) AS "FIRMA_REF",
        CAST(NULL AS VARCHAR) AS "FIRMA_SHOW_AS",
        CAST(NULL AS NUMBER(18,6)) AS "KURZ",
        CAST(NULL AS NUMBER(18,6)) AS "KURZ_MNOZSTVI",
        CAST(NULL AS VARCHAR) AS "MENA",
        CAST(NULL AS VARCHAR) AS "MENA_REF",
        CAST(NULL AS VARCHAR) AS "MENA_SHOW_AS",
        CAST(NULL AS VARCHAR) AS "MODUL",
        CAST(NULL AS VARCHAR) AS "MODUL_K",
        CAST(NULL AS VARCHAR) AS "MODUL_K_SHOW_AS",
        CAST(NULL AS VARCHAR) AS "NAZ_FIRMY",
        CAST(NULL AS VARCHAR) AS "DIC",
        CAST(NULL AS VARCHAR) AS "POPIS",
        CAST(NULL AS VARCHAR) AS "VAR_SYM",
        CAST(NULL AS VARCHAR) AS "TYP_SZB_DPH_K",
        CAST(NULL AS VARCHAR) AS "TYP_SZB_DPH_K_SHOW_AS",
        CAST(NULL AS NUMBER(18,6)) AS "SZB_DPH",
        CAST("SUM_TUZ" * -1 AS NUMBER(18, 2)) AS "SUM_TUZ",
        CAST(NULL AS NUMBER(18,2)) AS "SUM_MEN",
        CAST(NULL AS VARCHAR) AS "STAV_UZIV_K",
        CAST(NULL AS VARCHAR) AS "STAV_UZIV_K_SHOW_AS",
        CAST(NULL AS VARCHAR) AS "STREDISKO",
        CAST(NULL AS VARCHAR) AS "STREDISKO_REF",
        CAST(NULL AS VARCHAR) AS "STREDISKO_SHOW_AS",
        CAST(NULL AS VARCHAR) AS "ID_DOKL",
        CAST(NULL AS BOOLEAN) AS "ZUCTOVANO",
        CAST(NULL AS BOOLEAN) AS "VAT_ITEM",
        CAST(NULL AS BOOLEAN) AS "ACCOUNTS_SWAPPED",
        CAST(NULL AS VARCHAR) AS "ZAKAZKA",
        CAST(NULL AS VARCHAR) AS "ZAKAZKA_REF",
        CAST(NULL AS VARCHAR) AS "ZAKAZKA_SHOW_AS",
        CAST(NULL AS VARCHAR) AS "PAR_SYMBOL",
        CAST(NULL AS VARCHAR) AS "CINNOST",
        CAST(NULL AS VARCHAR) AS "CINNOST_REF",
        CAST(NULL AS VARCHAR) AS "CINNOST_SHOW_AS",
        CAST(NULL AS VARCHAR) AS "ID_POLOZEK",
        CAST(NULL AS BOOLEAN) AS "BEZ_POLOZEK"
    FROM {{ source('l2_input', 'PS_UCETNI_DENIK') }}
)

SELECT * FROM kept
UNION ALL
SELECT * FROM ps_rows
